// ---------------- choosing the language ----------------
let current = 'en';
let saved = null;     // the player's choice, from profile.settings.lang
let portal = null;    // the portal's locale, known only after its SDK has started
let browser = null;   // navigator.language

// 'es-MX' -> 'es', 'pt-PT' -> 'pt-BR', 'ja-JP' -> null
export function mapLocale(code) {
    if (!code || typeof code !== 'string') return null;
    const clean = code.trim().replace(/_/g, '-').toLowerCase();
    const base = clean.split('-')[0];
    if (base === 'pt') return 'pt-BR';
    if (base === 'in') return 'id'; // the old code for Indonesian, still reported by some Android browsers
    return TABLE[base] ? base : null;
}

function resolve() {
    if (saved && TABLE[saved]) return saved;
    return mapLocale(portal) || mapLocale(browser) || 'en';
}

export function getLang() { return current; }

// Start-up: the saved choice (if any) and the browser's language
export function initLanguage(opts) {
    saved = opts.saved || null;
    browser = opts.browser || null;
    current = resolve();
    return current;
}

// The player picked a language
export function setSavedLang(id) {
    saved = id;
    current = resolve();
    return current;
}

// The portal's SDK is ready. Returns true if this changed the language.
export function setPortalLocale(locale) {
    portal = locale || null;
    const before = current;
    current = resolve();
    return current !== before;
}

// ---------------- reading the table ----------------
export function t(key, vars) {
    const table = TABLE[current];
    let s = table && table[key];
    if (s === undefined) s = TABLE.en[key];
    if (s === undefined) return key;
    if (!vars) return s;
    return s.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m));
}

// A string with a number in it: picks key_one or key_other by the language's rule, and fills in {n}
export function tn(key, n, vars) {
    let one = n === 1;
    try { one = new Intl.PluralRules(current).select(n) === 'one'; } catch (e) { /* keep the simple rule */ }
    return t(key + (one ? '_one' : '_other'), { n, ...vars });
}

const ESC = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };

// The HTML for a hint: [WASD] becomes a key cap
export function keyHtml(text) {
    return String(text).replace(/[&<>"']/g, (c) => ESC[c]).replace(/\[([^\]]+)\]/g, '<kbd>$1</kbd>');
}

// Fills in everything on the page marked with data-i18n (text), data-i18n-keys (text with
// key caps), data-i18n-placeholder and data-i18n-aria
export function applyDom(root = document) {
    root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.getAttribute('data-i18n')); });
    root.querySelectorAll('[data-i18n-keys]').forEach((el) => { el.innerHTML = keyHtml(t(el.getAttribute('data-i18n-keys'))); });
    root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder'))); });
    root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria'))); });
    document.documentElement.setAttribute('lang', current);
}
